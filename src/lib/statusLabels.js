const LAP_STATUS = /^\+(\d+) Laps?$/;

export function statusLabel(status) {
  if (status == null || String(status).trim() === '') return 'Non enregistré';
  const text = String(status).trim();
  const laps = LAP_STATUS.exec(text);
  if (laps) {
    const count = Number(laps[1]);
    return `+${count} tour${count > 1 ? 's' : ''}`;
  }
  return STATUS_LABELS[text] ?? text;
}

export function hasStatusLabel(status) {
  return Object.hasOwn(STATUS_LABELS, status) || LAP_STATUS.test(status);
}
